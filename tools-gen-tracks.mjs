// Writes server/src/tracks.js: each map's centreline (x,z every ~2 m) and edge, for the lap verifier.
import * as THREE from 'three';
import fs from 'fs';
import { MAPS, ctrlHeights } from './src/maps.js';
import { cityBranches, resample } from './src/paths.js';
const out = {};
for (const [id, cfg] of Object.entries(MAPS)) {
  const H = ctrlHeights(cfg.ctrl);
  const c = new THREE.CatmullRomCurve3(cfg.ctrl.map((p, i) => new THREE.Vector3(p[0], H[i], p[1])), true, 'centripetal');
  const N = Math.round(c.getLength() / 2), x = [], z = [];
  for (let i = 0; i < N; i++) { const p = c.getPointAt(i / N); x.push(+p.x.toFixed(2)); z.push(+p.z.toFixed(2)); }
  out[id] = { edge: cfg.half + cfg.curb, x, z };
  // side roads: their centreline, and the main-loop samples where they leave and rejoin
  if (cfg.branches) out[id].branches = cityBranches(cfg).map(b => {
    const p = resample(b.pts, 2), near = (px, pz) => { let bi = 0, bd = 1e18; for (let i = 0; i < N; i++) { const d = (x[i] - px) ** 2 + (z[i] - pz) ** 2; if (d < bd) { bd = d; bi = i; } } return bi; };
    return { edge: b.half + cfg.curb, i0: near(p[0][0], p[0][1]), i1: near(p.at(-1)[0], p.at(-1)[1]), x: p.map(q => +q[0].toFixed(2)), z: p.map(q => +q[1].toFixed(2)) };
  });
}
fs.writeFileSync('server/src/tracks.js', '// generated by tools-gen-tracks.mjs — do not edit\nexport const TRACKS = ' + JSON.stringify(out) + ';\n');
console.log(Object.entries(out).map(([k, v]) => k + ':' + v.x.length).join(' '));
